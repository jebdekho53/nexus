'use strict';
// Splits a very large straight-line function (the application bootstrap f1) into ordered module parts.
//
//  * leading statement runs are peeled out of top-level labelled blocks (a block that starts with plain statements
//    behaves identically when those statements run just before it), and long runs are cut at statement boundaries;
//  * consecutive items are grouped into parts of roughly `target` printed lines;
//  * variables used by more than one part (accumulator, ctx, registers) are carried in a frame object `s`: each part
//    loads the ones it uses on entry and stores them on exit; variables private to a part are plain locals.
//  * only the last part may return.
const{compileTree}=require('./compile.cjs');
const{print}=require('./print.cjs');
const{tokenize}=require('./optimize.cjs');

const VARIABLE=/^(acc|pending|ctx|self|r\d+)$/;

// Does any node of `items` satisfy `test`?
function contains(items,test) {
  for(const item of items) {
    if(test(item))return true;
    const children=[item.body,item.then,item.else,item.handler,item.otherwise,...(item.cases??[]).map(entry=>entry[1])];
    for(const child of children)if(Array.isArray(child)&&contains(child,test))return true;
  }
  return false;
}

// L:while(true){ if(T){ EXIT } else { BODY; continue L } }  ==>  X:{ L:while(true){ if(T){ break X } else { BODY } } } EXIT
// (EXIT never continues L, so running it after the loop is the same program.) Repeated for the trailing loop.
function hoistLoopExits(items) {
  let out=[...items];
  for(;;) {
    const last=out[out.length-1];
    if(!last||last.k!=='loop'||last.body.length!==1||last.body[0].k!=='if')break;
    const branch=last.body[0];
    const continues=side=>contains(side,item=>item.k==='continue'&&item.label===last.label);
    const exitSide=!continues(branch.then)?'then':!continues(branch.else)?'else':null;
    if(!exitSide)break;
    const label='X'+last.label.slice(1);
    const exit=branch[exitSide];
    const stay=branch[exitSide==='then'?'else':'then'];
    const test=exitSide==='then'?branch.test:'!('+branch.test+')';
    const loop={...last,body:[{k:'if',test,then:[{k:'break',label}],else:stay}]};
    out=[...out.slice(0,-1),{k:'block',label,body:[loop]},...exit];
  }
  return out;
}

function peel(items) {
  const out=[];
  for(const item of items) {
    if(item.k==='block'&&item.body.length>=2&&item.body[0].k==='stmts') {
      out.push(item.body[0]);
      out.push(...peel([{...item,body:item.body.slice(1)}]));
    } else out.push(item);
  }
  return out;
}

function cut(items,maxLines) {
  const out=[];
  for(const item of items) {
    if(item.k!=='stmts'||item.lines.length<=maxLines){out.push(item);continue;}
    for(let at=0;at<item.lines.length;at+=maxLines)out.push({k:'stmts',lines:item.lines.slice(at,at+maxLines)});
  }
  return out;
}

const sizeOf=item=>print([item],{}).split('\n').length;

function splitDefinition(definition,options={}) {
  const target=options.target??1000;
  const{tree,isAsync,incoming}=compileTree(definition,options);
  if(isAsync)throw new Error('async functions are not split');
  const items=cut(peel(hoistLoopExits(peel(tree))),Math.floor(target*0.8));
  const groups=[];
  let current=[],size=0;
  for(const item of items) {
    const lines=sizeOf(item);
    if(current.length&&size+lines>target){groups.push(current);current=[];size=0;}
    current.push(item);size+=lines;
  }
  if(current.length)groups.push(current);
  const bodies=groups.map(group=>print(group,options));
  const used=bodies.map(body=>new Set(tokenize(body).map(token=>token.s).filter(name=>VARIABLE.test(name))));
  const counts=new Map();
  for(const set of used)for(const name of set)counts.set(name,(counts.get(name)??0)+1);
  const shared=new Set([...counts].filter(([,count])=>count>1).map(([name])=>name));
  if(incoming!==null)shared.add('r'+incoming);
  shared.add('ctx');shared.add('acc');shared.add('pending');
  const order=names=>[...names].sort((a,b)=>(a==='acc'?-3:a==='pending'?-2:a==='ctx'?-1:0)-(b==='acc'?-3:b==='pending'?-2:b==='ctx'?-1:0)||(Number(a.slice(1))||0)-(Number(b.slice(1))||0));
  const parts=bodies.map((body,index)=>{
    const tokens=tokenize(body).map(token=>token.s);
    if(index<bodies.length-1&&tokens.includes('return'))throw new Error('return inside non-final part '+(index+1));
    const names=order(used[index]);
    const carried=names.filter(name=>shared.has(name)&&name!=='self');
    const local=names.filter(name=>!shared.has(name)&&name!=='self');
    const lines=[
      "'use strict';",
      '// '+definition.id+' bootstrap, part '+(index+1)+' of '+bodies.length+' (generated by tools/compiler/split.cjs; do not edit).',
      'module.exports=function '+definition.id+'_part'+String(index+1).padStart(2,'0')+'(rt,fn,self,args,newTarget,K,s){',
      '  const{HOLE}=rt;',
    ];
    if(carried.length)lines.push('  let '+carried.map(name=>name+'=s.'+name).join(',')+';');
    if(local.length)lines.push('  let '+local.join(',')+';');
    lines.push(body);
    if(index<bodies.length-1||true) {
      // the last part returns before it can store; parts that fall through store their carried variables
    }
    return{name:definition.id+'-'+String(index+1).padStart(2,'0')+'.cjs',carried,lines,last:index===bodies.length-1};
  });
  // store carried variables on exit (the last part returns directly)
  for(const part of parts)if(!part.last)part.lines.push('  '+part.carried.map(name=>'s.'+name+'='+name+';').join(''));
  const finish=part=>part.lines.concat(['};']).join('\n')+'\n';
  const initial=['ctx','acc:undefined','pending:rt.HOLE',...(incoming!==null?['r'+incoming+':newTarget']:[])];
  const main=[
    "'use strict';",
    '// '+definition.id+': application bootstrap. The original function is one very large initialisation sequence; it is',
    '// split into ordered parts that carry their live variables in the frame object `s`.',
    ...parts.map((part,index)=>'const part'+(index+1)+'=require("./'+part.name+'");'),
    'module.exports=function '+definition.id+'(rt,fn,self,args,newTarget,ctx,K){',
    '  const s={'+initial.join(',')+'};',
    ...parts.slice(0,-1).map((part,index)=>'  part'+(index+1)+'(rt,fn,self,args,newTarget,K,s);'),
    '  return part'+parts.length+'(rt,fn,self,args,newTarget,K,s);',
    '};',
    '',
  ].join('\n');
  return{main,parts:parts.map(part=>({name:part.name,source:finish(part)}))};
}

// Definitions compiled as split modules (see build.cjs and differential.cjs).
const SPLIT_IDS=new Set(['f1']);

// Evaluates a split result in memory: returns the composed function.
function loadSplit(result) {
  const sources=new Map(result.parts.map(part=>[part.name,part.source]));
  const cache=new Map();
  const load=(name,source)=>{
    if(cache.has(name))return cache.get(name);
    const module={exports:{}};
    new Function('module','exports','require','"use strict";'+source)(module,module.exports,request=>load(request.replace('./',''),sources.get(request.replace('./',''))));
    cache.set(name,module.exports);
    return module.exports;
  };
  return load('main.cjs',result.main);
}

module.exports={splitDefinition,loadSplit,SPLIT_IDS};
